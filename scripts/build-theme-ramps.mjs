/* =============================================================================
   build-theme-ramps.mjs — the shipped themes' display ramps, for the Font Lab
   =============================================================================
   The Font Lab's "prefill from an existing ramp" control needs the ramps the
   system actually ships. Reading them out of css/themes.css keeps the two from
   drifting: add a theme, re-run this, and it is in the picker.

   Run:  npm run build:theme-ramps
   Out:  tools/font-lab/theme-ramps.js
   ============================================================================= */

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(join(ROOT, 'css', 'themes.css'), 'utf8')
          + readFileSync(join(ROOT, 'css', 'design-tokens-master.css'), 'utf8')

const STEPS = ['100', '200', '300', '400', '500', '600', '700', '800', '900']
const ramps = {}

for (const m of css.replace(/\/\*[\s\S]*?\*\//g, '')
       .matchAll(/(?:\[data-theme="([\w-]+)"\]|(:root))\s*\{([^{}]*)\}/g)) {
  const slug = m[1] ?? 'base'
  const body = m[3]
  const get = t => (body.match(new RegExp(`--${t}\\s*:\\s*([^;]+);`)) ?? [])[1]?.trim()
  const font = get('display-font')
  if (!font) continue
  const sizes = {}
  for (const s of STEPS) {
    const v = get(`display-size-${s}`)
    if (v) sizes[s] = parseFloat(v)
  }
  if (Object.keys(sizes).length !== STEPS.length) continue
  ramps[slug] = {
    name: slug === 'base' ? 'Base' : slug[0].toUpperCase() + slug.slice(1),
    font: font.split(',')[0].replace(/['"]/g, '').trim(),
    weight: get('display-weight') ?? '400',
    letterSpacing: get('display-letter-spacing') ?? '0em',
    sizes,
  }
}

const lh = { 900: 76, 800: 68, 700: 60, 600: 52, 500: 44, 400: 36, 300: 28, 200: 24, 100: 20 }
writeFileSync(join(ROOT, 'tools', 'font-lab', 'theme-ramps.js'),
  '// GENERATED by scripts/build-theme-ramps.mjs from css/themes.css — do not edit.\n' +
  `window.THEME_RAMPS = ${JSON.stringify(ramps)};\n` +
  `window.DISPLAY_LINEHEIGHTS = ${JSON.stringify(lh)};\n`)

console.log(`theme-ramps.js — ${Object.keys(ramps).length} ramp(s): ${Object.keys(ramps).join(', ')}`)
